#!/usr/bin/env python3
"""Regenerate web/js/masters.js from the master Excel file.

Usage:  python3 tools/xlsx_to_masters.py Substation_And_Material.xlsx

Sheet SUBSTATION : SUBDIVISION | SUBSTATION | FEEDER                    (11 kV feeders)
Sheet POLE       : POLE_TYPE   | LENGTH_METRE
Sheet 33KV       : PRIMARY SUBSTATION | 33 KV LINE | SECTION | SUBSTATION
Substation names in 33KV are matched to the SUBSTATION sheet ignoring case/punctuation/spaces
(e.g. "J.B. GANJ_332272" == "J.B GANJ_332272") and the SUBSTATION-sheet spelling is stored.
"""
import json, re, sys, os, datetime
import openpyxl

def clean(v):
    return " ".join(str(v).split()) if v is not None else ""

def norm(s):
    return re.sub(r"[^A-Z0-9]", "", s.upper())

def main(path):
    wb = openpyxl.load_workbook(path, data_only=True)

    # ---- 11 kV hierarchy
    tree, sub_of = {}, {}
    for r in wb["SUBSTATION"].iter_rows(min_row=2, values_only=True):
        sd, ss, fd = (clean(x) for x in r[:3])
        if not (sd and ss and fd):
            continue
        feeders = tree.setdefault(sd, {}).setdefault(ss, [])
        if fd not in feeders:
            feeders.append(fd)
        sub_of[norm(ss)] = (ss, sd)
    tree = {sd: {ss: sorted(f) for ss, f in sorted(v.items())} for sd, v in sorted(tree.items())}

    # ---- poles
    poles = []
    for r in wb["POLE"].iter_rows(min_row=2, values_only=True):
        t, l = clean(r[0]), r[1]
        if not t or l is None:
            continue
        l = float(l)
        poles.append({"type": t, "length": l, "label": f"{t} {('%g' % l)} m"})

    # ---- 33 kV: primary -> line -> section -> [substations]
    lines33, problems = {}, []
    for i, r in enumerate(wb["33KV"].iter_rows(min_row=2, values_only=True), start=2):
        ps, ln, sec, ss = (clean(x) for x in r[:4])
        if not (ps and ln and sec and ss):
            if any(clean(x) for x in r[:4]):
                problems.append(f"33KV row {i}: incomplete row {r[:4]}")
            continue
        hit = sub_of.get(norm(ss))
        if not hit:
            problems.append(f"33KV row {i}: substation '{ss}' not found in SUBSTATION sheet (subdivision unknown)")
            continue
        canon, _sd = hit
        subs = lines33.setdefault(ps, {}).setdefault(ln, {}).setdefault(sec, [])
        if canon not in subs:
            subs.append(canon)
        if canon != ss:
            print(f"  note: 33KV row {i} substation '{ss}' matched to '{canon}'")
    if problems:
        sys.exit("ERROR:\n  " + "\n  ".join(problems) + "\nFix the Excel file and run again.")
    lines33 = {p: {l: dict(sorted(s.items())) for l, s in sorted(v.items())} for p, v in sorted(lines33.items())}

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "web", "js", "masters.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by tools/xlsx_to_masters.py on %s - do not edit by hand.\n" % datetime.date.today().isoformat())
        f.write("// Source: %s\n" % os.path.basename(path))
        f.write("// HIERARCHY: subdivision -> substation -> [11 kV feeders]\n")
        f.write("export const HIERARCHY = %s;\n\n" % json.dumps(tree, indent=1, ensure_ascii=False))
        f.write("// LINES33: primary substation -> 33 kV line -> section -> [substations]\n")
        f.write("export const LINES33 = %s;\n\n" % json.dumps(lines33, indent=1, ensure_ascii=False))
        f.write("export const POLES = %s;\n" % json.dumps(poles, indent=1, ensure_ascii=False))
    nf = sum(len(f) for v in tree.values() for f in v.values())
    nsec = sum(len(s) for v in lines33.values() for s in v.values())
    print(f"Wrote {out}: {len(tree)} subdivisions, {sum(len(v) for v in tree.values())} substations, {nf} feeders, "
          f"{len(lines33)} primary S/S, {sum(len(v) for v in lines33.values())} 33 kV lines, {nsec} sections, {len(poles)} pole specs")

if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
