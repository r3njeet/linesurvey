#!/usr/bin/env python3
"""Regenerate web/js/masters.js from the master Excel file.

Usage:  python3 tools/xlsx_to_masters.py Substation_And_Material.xlsx

Sheet SUBSTATION : columns SUBDIVISION | SUBSTATION | FEEDER
Sheet POLE       : columns POLE_TYPE   | LENGTH_METRE
"""
import json, sys, os, datetime
import openpyxl

def clean(v):
    return " ".join(str(v).split()) if v is not None else ""

def main(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    tree = {}
    for r in wb["SUBSTATION"].iter_rows(min_row=2, values_only=True):
        sd, ss, fd = (clean(x) for x in r[:3])
        if not (sd and ss and fd):
            continue
        feeders = tree.setdefault(sd, {}).setdefault(ss, [])
        if fd not in feeders:
            feeders.append(fd)
    # sort for nicer dropdowns
    tree = {sd: {ss: sorted(f) for ss, f in sorted(v.items())} for sd, v in sorted(tree.items())}

    poles = []
    for r in wb["POLE"].iter_rows(min_row=2, values_only=True):
        t, l = clean(r[0]), r[1]
        if not t or l is None:
            continue
        l = float(l)
        ls = ("%g" % l)
        poles.append({"type": t, "length": l, "label": f"{t} {ls} m"})

    out = os.path.join(os.path.dirname(__file__), "..", "web", "js", "masters.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by tools/xlsx_to_masters.py on %s - do not edit by hand.\n"
                % datetime.date.today().isoformat())
        f.write("// Source: %s\n" % os.path.basename(path))
        f.write("export const HIERARCHY = %s;\n\n" % json.dumps(tree, indent=1, ensure_ascii=False))
        f.write("export const POLES = %s;\n" % json.dumps(poles, indent=1, ensure_ascii=False))
    n = sum(len(f) for v in tree.values() for f in v.values())
    print(f"Wrote {out}: {len(tree)} subdivisions, {sum(len(v) for v in tree.values())} substations, {n} feeders, {len(poles)} pole specs")

if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
